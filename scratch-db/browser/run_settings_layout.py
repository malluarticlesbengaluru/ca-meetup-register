from admin_test import *
# Browser suite for the Settings layout on laptops: side menu, one group at a time, two columns, readiness count, remembered group; phones unchanged.
# Run:  cd scratch-db/browser && python3 run_settings_layout.py | tail -1      (set SHOTS=/some/folder to also save screenshots)
SHOTS = os.environ.get('SHOTS')
def shot(pg, name):
    if SHOTS: pg.screenshot(path=f'{SHOTS}/{name}.png', full_page=False)
def vis(pg, sel): return pg.evaluate("s=>{const e=document.querySelector(s);if(!e)return false;const r=e.getBoundingClientRect();return r.width>0&&r.height>0&&getComputedStyle(e).visibility!='hidden'}", sel)
def titles(pg): return pg.evaluate("()=>[...document.querySelectorAll('.spane.on .card h2')].filter(h=>h.getBoundingClientRect().width>0).map(h=>h.textContent)")
with sync_playwright() as p:
    b, pg, errs = open_page(p, db(), 'settings'); pg.wait_for_timeout(300)
    names = pg.evaluate("[...document.querySelectorAll('#sside .sgb')].map(x=>x.firstChild.textContent)")
    check('L1 laptop: side menu lists the six groups in order', names == ['Set-up','Transfers','Event day','Go-live check','Other','Log'], names)
    check('L2 laptop: the old chip bar is hidden, the side menu is shown', not vis(pg,'#snav') and vis(pg,'#sside'))
    t = titles(pg)
    check('L3 laptop: Set-up shows Registration, Payment, Contacts and Event details, and nothing else', sorted(t) == sorted(['Registration settings','Payment details','Contacts','Event details']) or (set(t) >= {'Registration settings','Event details'} and 'Photos' not in t and 'Settings log' not in t), t)
    cols = pg.evaluate("[...document.querySelectorAll('.spane.on .scol')].map(c=>Math.round(c.getBoundingClientRect().left))")
    check('L4 laptop: cards sit in two columns', len(set(cols)) == 2, cols)
    shot(pg, 'laptop_setup')
    pg.click('#sside [data-sg="event"]'); pg.wait_for_timeout(150)
    t = titles(pg)
    check('L5 laptop: Event day shows Attendee space, Photos, Videos and Space sharing only', sorted(t) == ['Attendee space','Photos','Space sharing','Videos'], t)
    check('L6 laptop: the Registration card is hidden once another group is open', not vis(pg, '#ssave'))
    shot(pg, 'laptop_event')
    pg.click('#sside [data-sg="ready"]'); pg.wait_for_timeout(150)
    badge = pg.inner_text('#sside [data-sg="ready"]')
    check('L7 laptop: Go-live item shows a check count (SETTINGS has 5 of 6 ready? deadline is past, so expect an ✗ and a fraction)', re.search(r'[✓✗] \d/6', badge), badge)
    n_ticks = pg.evaluate("[...document.querySelectorAll('.spane.on .checks li span:first-child')].filter(s=>s.textContent==='✓').length")
    check('L8 laptop: the count on the menu equals the ticks in the list', ('✓ 6/6' in badge and n_ticks == 6) or f'{n_ticks}/6' in badge, (badge, n_ticks))
    shot(pg, 'laptop_ready')
    pg.click('#sside [data-sg="log"]'); pg.wait_for_timeout(150)
    w = pg.evaluate("(()=>{const c=document.querySelector('.spane.on .slog').getBoundingClientRect(),m=document.querySelector('.spanes').getBoundingClientRect();return [Math.round(c.width),Math.round(m.width)]})()")
    check('L9 laptop: the log uses the full width', abs(w[0]-w[1]) <= 2, w)
    pg.click('#sside [data-sg="other"]'); pg.wait_for_timeout(150)
    check('L10 laptop: Other holds Advanced and After the event', set(titles(pg)) == {'Advanced','After the event'}, titles(pg))
    # remembered group: leave and come back, and survive a re-render
    pg.click('#sside [data-sg="transfers"]'); pg.wait_for_timeout(100)
    go_tab(pg, 'overview'); go_tab(pg, 'settings'); pg.wait_for_timeout(200)
    check('L11 laptop: coming back opens the group used last', pg.get_attribute('#sside [aria-current]', 'data-sg') == 'transfers' and 'Ticket transfers' in titles(pg), titles(pg))
    # saving still works exactly as before
    pg.click('#sside [data-sg="setup"]'); pg.wait_for_timeout(100)
    pg.fill('#scap', '160'); pg.click('#ssave'); pg.wait_for_timeout(400)
    c = [x for x in pg.evaluate('window.__CALLS||[]') if x['name'] == 'admin_update_settings']
    check('L12 laptop: Save settings still sends the same database call with the typed cap', c and c[-1]['args']['p_cap'] == 160, c)
    check('L13 laptop: after saving, the group stays on Set-up', pg.get_attribute('#sside [aria-current]', 'data-sg') == 'setup')
    # pause box: collapsed when off, opens, and its fields still work
    pg.click('#pausedet summary'); pg.wait_for_timeout(100)
    check('L14 laptop: Daily pause is collapsed until opened (off by default)', pg.evaluate("document.querySelector('#pausedet').open") is True and vis(pg,'#spause'))
    check('L15 laptop: no page errors', not errs, errs); b.close()
    # pause on -> starts open
    s2 = dict(SETTINGS, pause_enabled=True)
    b, pg, errs = open_page(p, db(tables=dict(settings=s2)), 'settings'); pg.wait_for_timeout(200)
    check('L16 laptop: Daily pause starts open when it is switched on', vis(pg, '#spause') and pg.is_checked('#spause')); b.close()
    # a narrower laptop (1100 wide): still a side menu, two columns or one, nothing overflows sideways
    for label, vp in [('laptop 1280', (1280, 720)), ('laptop 1100', (1100, 700)), ('big 1592', (1592, 910))]:
        b, pg, errs = open_page(p, db(), 'settings'); pg.set_viewport_size({'width': vp[0], 'height': vp[1]}); pg.wait_for_timeout(250)
        ov = pg.evaluate("document.documentElement.scrollWidth - document.documentElement.clientWidth")
        check(f'L17 {label}: no sideways scrolling', ov <= 1, ov); shot(pg, 'w%d' % vp[0]); b.close()
    # phone: exactly as before (chip bar, every card on one page, old order)
    b = p.chromium.launch(); pg = b.new_page(viewport={'width':390,'height':800}); errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.route('**/*', lambda r: (r.fulfill(body=HTML, content_type='text/html') if r.request.url.endswith('/admin/test.html') else r.fulfill(body='/*stub*/', content_type='text/javascript') if r.request.url.endswith('.js') or '/npm/' in r.request.url else r.fulfill(status=204, body='')))
    pg.add_init_script('window.__DB=' + json.dumps(db()) + ';'); pg.add_init_script(MOCK); pg.add_init_script(CH); pg.add_init_script(DLG_BOT)
    pg.goto('https://example.test/admin/test.html'); pg.wait_for_selector('#v'); go_tab(pg, 'settings'); pg.wait_for_timeout(300)
    check('P1 phone: chip bar shown, side menu hidden', vis(pg,'#snav') and not vis(pg,'#sside'))
    order = pg.evaluate("[...document.querySelectorAll('#snav .chip')].map(c=>c.textContent)")
    check('P2 phone: chips keep the old order', order == ['Registration','Payment','Contacts','Event','Transfers','Readiness','Advanced','After event','Attendee space','Photos','Videos','Space sharing','Log'], order)
    ys = pg.evaluate("[...document.querySelectorAll('.sc')].sort((a,b)=>a.style.order-b.style.order).map(c=>Math.round(c.getBoundingClientRect().top+scrollY))")
    check('P3 phone: all cards are on the page, stacked top to bottom in the old order', ys == sorted(ys) and len(ys) == 13, ys)
    shot(pg, 'phone')
    check('P4 phone: no page errors', not errs, errs); b.close()
print(f"{sum(results)} passed, {len(results)-sum(results)} failed")
